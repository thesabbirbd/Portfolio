/**
 * Converts Bijoy SutonnyMJ text to standard Unicode (UTF-8) Bangla.
 */
export function convertBijoyToUnicode(src: string): string {
  if (!src) return "";
  let text = src;

  // 1. Replace multi-character juktoborno
  for (const [bijoyChar, unicodeChar] of JUKTOBORNO_MAP) {
    text = text.split(bijoyChar).join(unicodeChar);
  }

  // 2. Handle Ref (©): In Bijoy, consonant + © -> র্ + consonant
  text = text.replace(/([ক-হa-zA-Z_])©/g, "র্$1");

  // 3. Handle pre-kar reordering (w = ি, ‡ = ে, ‰ = ৈ)
  // Bijoy types 'w' before the consonant/cluster, Unicode puts 'ি' after.
  text = text.replace(/w([a-zA-Z_ক-হ])/g, "$1w");
  text = text.replace(/‡([a-zA-Z_ক-হ])/g, "$1‡");
  text = text.replace(/‰([a-zA-Z_ক-হ])/g, "$1‰");

  // Now replace kars
  text = text.replace(/w/g, "ি");
  text = text.replace(/‡/g, "ে");
  text = text.replace(/‰/g, "ৈ");

  // 4. Character by character mapping for vowels, consonants, digits
  let result = "";
  let i = 0;
  while (i < text.length) {
    if (i + 1 < text.length && BIJOY_TO_UNICODE_MAP[text.slice(i, i + 2)]) {
      result += BIJOY_TO_UNICODE_MAP[text.slice(i, i + 2)];
      i += 2;
    } else if (BIJOY_TO_UNICODE_MAP[text[i]]) {
      result += BIJOY_TO_UNICODE_MAP[text[i]];
      i += 1;
    } else {
      result += text[i];
      i += 1;
    }
  }

  // Normalize Unicode Bangla characters (ensure hasant and ref binding)
  return result.normalize("NFC");
}

