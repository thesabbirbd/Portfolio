/**
 * Converts Unicode (UTF-8) Bangla text to Bijoy Classic (SutonnyMJ).
 */
export function convertUnicodeToBijoy(src: string): string {
  if (!src) return "";
  let text = src.normalize("NFC");

  // 1. First replace common composite characters
  for (const [uni, bij] of Object.entries(UNICODE_TO_BIJOY_MAP)) {
    if (uni.length > 1) {
      text = text.split(uni).join(bij);
    }
  }

  // 2. Handle Ref (র্): র্ + consonant -> consonant + ©
  text = text.replace(/র্([ক-হa-zA-Z_])/g, "$1©");

  // 3. Pre-kar reordering for Bijoy (ি -> w before, ে -> ‡ before, ৈ -> ‰ before, ো -> ‡...v)
  text = text.replace(/([ক-হa-zA-Z_¶ÁÎ³×Û])ো/g, "‡$1v");
  text = text.replace(/([ক-হa-zA-Z_¶ÁÎ³×Û])ৌ/g, "‡$1Š");
  text = text.replace(/([ক-হa-zA-Z_¶ÁÎ³×Û])ি/g, "w$1");
  text = text.replace(/([ক-হa-zA-Z_¶ÁÎ³×Û])ে/g, "‡$1");
  text = text.replace(/([ক-হa-zA-Z_¶ÁÎ³×Û])ৈ/g, "‰$1");

  // 4. Single character mapping
  let result = "";
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    result += UNICODE_TO_BIJOY_MAP[ch] !== undefined ? UNICODE_TO_BIJOY_MAP[ch] : ch;
  }

  return result;
}

/**
 * English digits to Bangla digits helper
 */
export function toBanglaDigits(num: number | string): string {
  const bnDigits = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];
  return String(num).replace(/\d/g, (d) => bnDigits[parseInt(d, 10)]);
}

