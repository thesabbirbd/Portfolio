/**
 * THE SABBiR OS // Visual Snapshot Generator
 * Generates crisp, high-contrast 1200×630 Branded Visual Result Cards (PNG/SVG Data URLs).
 * Eliminates raw code dumps on /s/[token] by presenting visual deliverables front & center.
 */

export interface VisualCardOptions {
  title: string;
  toolSlug: string;
  creatorName: string;
  highlights?: Array<{ label: string; value: string }>;
  accentColor?: string; // hex e.g. #F59E0B
  dateStr?: string;
}

export function generateSvgDataUrl(options: VisualCardOptions): string {
  const {
    title,
    toolSlug,
    creatorName,
    highlights = [],
    accentColor = "#F59E0B",
    dateStr = new Date().toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" }),
  } = options;

  const safeTitle = title.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const safeCreator = creatorName.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const safeSlug = toolSlug.replace(/-/g, " ").toUpperCase();

  // Highlight tiles (up to 4)
  const renderedTiles = highlights.slice(0, 4).map((h, i) => {
    const x = 80 + i * 260;
    const safeLabel = h.label.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
    const safeVal = h.value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

    return `
      <g transform="translate(${x}, 340)">
        <rect width="240" height="90" rx="16" fill="#18181B" stroke="#27272A" stroke-width="1.5"/>
        <text x="20" y="34" fill="#A1A1AA" font-family="sans-serif" font-size="12" font-weight="600" text-transform="uppercase">${safeLabel}</text>
        <text x="20" y="68" fill="#F4F4F5" font-family="monospace" font-size="20" font-weight="bold">${safeVal}</text>
      </g>
    `;
  }).join("\n");

  const svg = `<svg width="1200" height="630" viewBox="0 0 1200 630" fill="none" xmlns="http://www.w3.org/2000/svg">
    <defs>
      <linearGradient id="cardBg" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="#0A0A0C"/>
        <stop offset="50%" stop-color="#121217"/>
        <stop offset="100%" stop-color="#0A0A0C"/>
      </linearGradient>
      <radialGradient id="meshGlow" cx="90%" cy="10%" r="55%">
        <stop offset="0%" stop-color="${accentColor}" stop-opacity="0.22"/>
        <stop offset="100%" stop-color="#000000" stop-opacity="0"/>
      </radialGradient>
      <filter id="shadow" x="-10%" y="-10%" width="120%" height="120%">
        <feDropShadow dx="0" dy="12" stdDeviation="24" flood-color="#000000" flood-opacity="0.6"/>
      </filter>
    </defs>

    <!-- Main Canvas -->
    <rect width="1200" height="630" fill="url(#cardBg)"/>
    <rect width="1200" height="630" fill="url(#meshGlow)"/>

    <!-- Subtle Inner Border Frame -->
    <rect x="32" y="32" width="1136" height="566" rx="28" stroke="#27272A" stroke-width="2"/>

    <!-- Top Badge Strip -->
    <g transform="translate(80, 72)">
      <rect width="220" height="34" rx="17" fill="${accentColor}" fill-opacity="0.15" stroke="${accentColor}" stroke-opacity="0.35"/>
      <text x="110" y="22" fill="${accentColor}" font-family="monospace" font-size="12" font-weight="bold" text-anchor="middle" letter-spacing="1">STUDIO SNAPSHOT</text>
      <text x="240" y="22" fill="#71717A" font-family="sans-serif" font-size="13">• ${safeSlug}</text>
    </g>

    <!-- Title & Creator Info -->
    <text x="80" y="180" fill="#FFFFFF" font-family="sans-serif" font-size="44" font-weight="800" letter-spacing="-1">${safeTitle}</text>
    
    <g transform="translate(80, 220)">
      <text x="0" y="20" fill="#A1A1AA" font-family="sans-serif" font-size="16">Generated by <tspan fill="#FFFFFF" font-weight="bold">${safeCreator}</tspan> on ${dateStr}</text>
    </g>

    <!-- Highlight Metric Cards -->
    ${renderedTiles}

    <!-- Bottom Footer Watermark & Branding -->
    <g transform="translate(80, 520)">
      <circle cx="16" cy="16" r="16" fill="${accentColor}" fill-opacity="0.2"/>
      <text x="16" y="21" fill="${accentColor}" font-family="sans-serif" font-size="14" font-weight="bold" text-anchor="middle">S</text>
      <text x="44" y="22" fill="#F4F4F5" font-family="sans-serif" font-size="16" font-weight="bold">THE SABBiR OS</text>
      <text x="180" y="22" fill="#71717A" font-family="monospace" font-size="14">· 24h Ephemeral Workplace</text>
      <text x="1040" y="22" fill="#A1A1AA" font-family="monospace" font-size="13" text-anchor="end">sabbir.nav.bd/s</text>
    </g>
  </svg>`;

  const base64Svg = Buffer.from(svg).toString("base64");
  return `data:image/svg+xml;base64,${base64Svg}`;
}

/**
 * Parses studio payload into key-value highlights for visual card preview
 */
export function extractHighlights(payloadOrJson: string | Record<string, unknown> | null | undefined): Array<{ label: string; value: string }> {
  if (!payloadOrJson) return [];

  let payload: Record<string, unknown>;
  if (typeof payloadOrJson === "string") {
    if (!payloadOrJson.trim()) return [];
    try {
      payload = JSON.parse(payloadOrJson);
    } catch {
      return [{ label: "Content", value: payloadOrJson.slice(0, 30) }];
    }
  } else {
    payload = payloadOrJson;
  }

  if (typeof payload !== "object" || payload === null) {
    return [];
  }

  const highlights: Array<{ label: string; value: string }> = [];

  for (const [key, val] of Object.entries(payload)) {
    if (typeof val === "string" && val.length > 0 && val.length < 35 && !val.startsWith("data:")) {
      highlights.push({ label: key.replace(/([A-Z])/g, " $1"), value: val });
    } else if (typeof val === "number") {
      highlights.push({ label: key.replace(/([A-Z])/g, " $1"), value: String(val) });
    }
    if (highlights.length >= 4) break;
  }

  return highlights;
}

export const extractPayloadHighlights = extractHighlights;
